#!/usr/bin/env python3
"""
make_captions.py — "Center-Punch" caption generator (ASS / libass).

Recreates the caption grammar measured on the reference channel
(see docs/05_PRESET_SPECIFICATION.md §1):

  * 1–3 words per chunk, UPPERCASE, heavy geometric sans (Montserrat Black)
  * neon-green fill (#19F464 sampled), dark-green hard drop shadow (down-offset)
  * soft green glow, thin dark outline
  * block vertically centred at 50 % of frame height (measured: 0.501)
  * persistent two-tone, wide-tracked brand watermark directly under the caption
  * profanity masking (F*** style) and *NON-SPEECH* tags, both observed

Input  : word-level timestamps, either
         - JSON  : [{"word": "hello", "start": 0.12, "end": 0.40}, ...]
                   (also accepts openai-whisper / faster-whisper / WhisperX
                    output with {"segments":[{"words":[...]}]})
         - SRT   : cue text is split into words, time spread evenly in the cue
Output : .ass file you can burn in with FFmpeg, import in Resolve / Premiere
         (via an ASS→SRT/caption import) or use as a timing guide in CapCut.

Usage:
  python3 make_captions.py words.json out.ass --brand "YOURBRAND" --accent-split 4
  ffmpeg -i edit.mp4 -vf "ass=out.ass" -c:a copy captioned.mp4

Stdlib only. Python 3.8+.
"""
import argparse
import json
import re
import sys
from pathlib import Path

# ---------------------------------------------------------------- constants
PLAY_W, PLAY_H = 1080, 1920

# ASS colours are &HAABBGGRR
def ass_color(hex_rgb: str, alpha: int = 0) -> str:
    h = hex_rgb.lstrip("#")
    r, g, b = h[0:2], h[2:4], h[4:6]
    return f"&H{alpha:02X}{b}{g}{r}".upper()

FILL = "#19F464"        # sampled median fill (44 frames)
SHADOW = "#0A3D16"      # inferred core of the extruded shadow (sampled mean incl. bleed: #04651C)
OUTLINE = "#06260D"     # thin dark rim
GLOW = "#19F464"
WM_LIGHT = "#E6E2DE"    # watermark light part (sampled #C6C2BE over footage, ~80 % opacity)
WM_ACCENT = "#54BB6F"   # watermark accent part (sampled, semi-transparent)

PROFANITY = {
    "fuck": "F***", "fucking": "F***ING", "fucked": "F***ED", "shit": "S***",
    "bitch": "B****", "ass": "A**", "damn": "D***",
}

HEADER = """[Script Info]
; Generated by make_captions.py — Center-Punch caption system
ScriptType: v4.00+
PlayResX: {w}
PlayResY: {h}
WrapStyle: 2
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: CapGlow,{font},{size},{glow_a},&H000000FF,{glow_a},&HFF000000,0,0,0,0,100,100,{spacing},0,1,{glow_bord},0,5,60,60,0,1
Style: Cap,{font},{size},{fill},&H000000FF,{outline},{shadow},0,0,0,0,100,100,{spacing},0,1,{bord},0,5,60,60,0,1
Style: Brand,{wm_font},{wm_size},{wm_light},&H000000FF,&HFF000000,&HB4000000,0,0,0,0,100,100,{wm_spacing},0,1,0,0,5,60,60,0,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""


def ts(t: float) -> str:
    t = max(0.0, t)
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = t % 60
    return f"{h}:{m:02d}:{s:05.2f}"


# ---------------------------------------------------------------- input
def load_words(path: Path):
    text = path.read_text(encoding="utf-8")
    if path.suffix.lower() == ".srt":
        return words_from_srt(text)
    data = json.loads(text)
    if isinstance(data, dict) and "segments" in data:
        out = []
        for seg in data["segments"]:
            for w in seg.get("words", []):
                out.append({"word": w.get("word", w.get("text", "")).strip(),
                            "start": float(w["start"]), "end": float(w["end"])})
        return out
    return [{"word": str(w["word"]).strip(), "start": float(w["start"]), "end": float(w["end"])} for w in data]


def words_from_srt(text: str):
    out = []
    blocks = re.split(r"\n\s*\n", text.strip())
    tre = re.compile(r"(\d+):(\d+):(\d+)[,.](\d+)\s*-->\s*(\d+):(\d+):(\d+)[,.](\d+)")
    for b in blocks:
        lines = b.strip().splitlines()
        tl = next((l for l in lines if "-->" in l), None)
        if not tl:
            continue
        m = tre.search(tl)
        g = list(map(int, m.groups()))
        st = g[0] * 3600 + g[1] * 60 + g[2] + g[3] / 1000
        en = g[4] * 3600 + g[5] * 60 + g[6] + g[7] / 1000
        body = " ".join(lines[lines.index(tl) + 1:])
        ws = body.split()
        if not ws:
            continue
        step = (en - st) / len(ws)
        for i, w in enumerate(ws):
            out.append({"word": w, "start": st + i * step, "end": st + (i + 1) * step})
    return out


# ---------------------------------------------------------------- chunking
def clean(word: str, censor: bool) -> str:
    w = word.strip()
    core = re.sub(r"[^\w']", "", w).lower()
    if censor and core in PROFANITY:
        return PROFANITY[core]
    w = re.sub(r"[\"“”]", "", w)
    w = re.sub(r"[,.;:]+$", "", w)          # keep ? and ! (observed: "A CROCODILE?")
    return w.upper()


SHORT_FUNCTION = {"a", "an", "the", "of", "to", "in", "on", "at", "is", "it", "be", "as", "by", "or", "and", "so"}


def _bare(w):
    return re.sub(r"[^\w']", "", w["word"]).lower()


def chunk_words(words, max_words=3, max_chars=16, min_dur=0.18, long_word=9):
    """1–3 word chunking tuned to the measured distribution (1w 37 %, 2w 48 %, 3w 14 %; mean 1.79):
       * a 3rd word is only allowed when it is a short function word ("ALL OF A", "ABOUT THE")
       * a long word (>= 9 letters) stands alone unless a short function word follows it ("ENCOURAGED TO")
       * break after clause punctuation and before overflowing max_chars."""
    chunks, cur = [], []
    for w in words:
        nxt_len = len(" ".join(x["word"] for x in cur + [w]))
        if cur and nxt_len > max_chars:
            chunks.append(cur)          # adding this word would overflow the line
            cur = []
        elif cur and len(cur) >= 2 and _bare(w) not in SHORT_FUNCTION:
            chunks.append(cur)          # 3rd word only if it is a tiny function word
            cur = []
        elif cur and len(_bare(cur[-1])) >= long_word and _bare(w) not in SHORT_FUNCTION:
            chunks.append(cur)          # long word stands alone
            cur = []
        elif cur and len(cur) == 1 and len(_bare(w)) >= long_word and _bare(cur[0]) not in SHORT_FUNCTION:
            chunks.append(cur)          # don't glue a long word onto a content word
            cur = []
        cur.append(w)
        ends_clause = bool(re.search(r"[,.!?;:]$", w["word"].strip()))
        if len(cur) >= max_words or ends_clause:
            chunks.append(cur)
            cur = []
    if cur:
        chunks.append(cur)
    out = []
    for i, c in enumerate(chunks):
        st = c[0]["start"]
        # hold each chunk until the next one starts (no empty frames between words),
        # unless there is a real pause > 0.6 s
        nxt = chunks[i + 1][0]["start"] if i + 1 < len(chunks) else c[-1]["end"] + 0.25
        en = nxt if nxt - c[-1]["end"] < 0.6 else c[-1]["end"] + 0.15
        en = max(en, st + min_dur)
        out.append((st, en, c))
    return out


# ---------------------------------------------------------------- render
def pop(anim: str) -> str:
    if anim == "none":
        return ""
    if anim == "pop":      # 85 % → 106 % → 100 % in ~130 ms
        return r"\fscx85\fscy85\t(0,70,\fscx106\fscy106)\t(70,130,\fscx100\fscy100)"
    if anim == "punch":    # harder: 70 % → 112 % → 100 %
        return r"\fscx70\fscy70\t(0,60,\fscx112\fscy112)\t(60,120,\fscx100\fscy100)"
    raise ValueError(anim)


def build(words, brand, accent_split, anim, censor, font, size, y_ratio,
          shadow_dy, shadow_dx, glow, wm, max_words):
    words = [dict(w, word=w["word"]) for w in words if w["word"].strip()]
    y = int(PLAY_H * y_ratio)
    x = PLAY_W // 2
    hdr = HEADER.format(
        w=PLAY_W, h=PLAY_H, font=font, size=size, spacing=0,
        fill=ass_color(FILL), outline=ass_color(OUTLINE), shadow=ass_color(SHADOW),
        glow_a=ass_color(GLOW, 0x9A), glow_bord=10, bord=2.2,
        wm_font=font.replace("Black", "ExtraBold"), wm_size=round(size * 0.40),
        wm_light=ass_color(WM_LIGHT, 0x30), wm_spacing=round(size * 0.14),
    )
    ev = []
    chunks = chunk_words(words, max_words=max_words)
    for st, en, c in chunks:
        txt = " ".join(clean(w["word"], censor) for w in c)
        if txt.startswith("*") or txt.startswith("["):  # non-speech tag e.g. *SOUNDS*
            txt = "*" + txt.strip("*[]") + "*"
        pos = rf"\an5\pos({x},{y})"
        if glow:
            ev.append(f"Dialogue: 0,{ts(st)},{ts(en)},CapGlow,,0,0,0,,{{{pos}{pop(anim)}\\blur12}}{txt}")
        # extruded drop shadow (mostly downward) — \xshad/\yshad give independent offsets
        ev.append(f"Dialogue: 1,{ts(st)},{ts(en)},Cap,,0,0,0,,{{{pos}{pop(anim)}\\xshad{shadow_dx}\\yshad{shadow_dy}}}{txt}")
    if wm and brand:
        end = max((e for _, e, _ in chunks), default=1.0)
        a, b = brand[:accent_split].upper(), brand[accent_split:].upper()
        wy = y + round(size * 0.68)   # measured: watermark centre sits 55–56 px below caption centre
        accent = ass_color(WM_ACCENT, 0x40)
        ev.append(f"Dialogue: 2,{ts(0)},{ts(end + 0.5)},Brand,,0,0,0,,{{\\an5\\pos({x},{wy})}}{a}{{\\1c{accent}}}{b}")
    return hdr + "\n".join(ev) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("words", type=Path, help="word-timestamp JSON or SRT")
    ap.add_argument("out", type=Path, help="output .ass")
    ap.add_argument("--brand", default="YOURBRAND", help="watermark text ('' to disable)")
    ap.add_argument("--accent-split", type=int, default=None,
                    help="index where the accent colour starts (default: last 4 letters)")
    ap.add_argument("--anim", choices=["pop", "punch", "none"], default="pop")
    ap.add_argument("--no-censor", action="store_true")
    ap.add_argument("--font", default="Montserrat Black")
    ap.add_argument("--size", type=int, default=82, help="font size in 1080x1920 units (calibrated: 82 → 42 px cap height, matches measured median 41 px)")
    ap.add_argument("--y", type=float, default=0.50, help="vertical centre as fraction of height")
    ap.add_argument("--shadow-dy", type=float, default=6)
    ap.add_argument("--shadow-dx", type=float, default=1.5)
    ap.add_argument("--max-words", type=int, default=3)
    ap.add_argument("--no-glow", action="store_true")
    ap.add_argument("--no-watermark", action="store_true")
    a = ap.parse_args()
    words = load_words(a.words)
    if not words:
        sys.exit("no words found")
    split = a.accent_split if a.accent_split is not None else max(0, len(a.brand) - 4)
    a.out.write_text(build(words, a.brand, split, a.anim, not a.no_censor, a.font, a.size,
                           a.y, a.shadow_dy, a.shadow_dx, not a.no_glow, not a.no_watermark,
                           a.max_words), encoding="utf-8")
    print(f"wrote {a.out} ({len(words)} words)")


if __name__ == "__main__":
    main()
